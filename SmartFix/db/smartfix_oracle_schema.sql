-- ==========================================================
-- SmartFix - Smart Device Maintenance Management System
-- Oracle Database DDL Schema
-- ==========================================================

-- 1. جدول المستخدمين (Users)
-- يُستخدم لتخزين بيانات العملاء، الفنيين، والمديرين مع أدوارهم (Roles) للصلاحيات.
CREATE TABLE Users (
    Id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Username VARCHAR2(100) NOT NULL UNIQUE,
    Email VARCHAR2(150) NOT NULL UNIQUE,
    PasswordHash VARCHAR2(500) NOT NULL,
    Role VARCHAR2(50) NOT NULL, -- 'Admin', 'Technician', 'Customer'
    PhoneNumber VARCHAR2(20),
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. جدول الأجهزة (Devices)
-- يمثل الأجهزة الذكية التي يمتلكها العملاء وتحتاج صيانة.
CREATE TABLE Devices (
    Id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DeviceName VARCHAR2(100) NOT NULL,    -- مثل: iPhone 15 Pro, Galaxy S24
    DeviceType VARCHAR2(50) NOT NULL,     -- مثل: Phone, Tablet, Laptop
    SerialNumber VARCHAR2(100) UNIQUE,
    CustomerId NUMBER NOT NULL,
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_device_customer FOREIGN KEY (CustomerId) REFERENCES Users(Id) ON DELETE CASCADE
);

-- 3. جدول تذاكر الصيانة (MaintenanceTickets)
-- جوهر النظام: يربط الجهاز بالعميل والفني المخصص، ويتابع حالة الصيانة.
CREATE TABLE MaintenanceTickets (
    Id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TicketNumber VARCHAR2(50) NOT NULL UNIQUE, -- رقم مرجعي فريد مثل TCK-2026-001
    DeviceId NUMBER NOT NULL,
    CustomerId NUMBER NOT NULL,
    TechnicianId NUMBER,
    IssueDescription CLOB NOT NULL,           -- وصف المشكلة بالتفصيل
    Status VARCHAR2(50) DEFAULT 'Pending',    -- Pending, InProgress, WaitingForParts, Repaired, Delivered, Cancelled
    Priority VARCHAR2(20) DEFAULT 'Medium',   -- Low, Medium, High, Urgent
    EstimatedCost NUMBER(10, 2),
    FinalCost NUMBER(10, 2),
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UpdatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ticket_device FOREIGN KEY (DeviceId) REFERENCES Devices(Id),
    CONSTRAINT fk_ticket_customer FOREIGN KEY (CustomerId) REFERENCES Users(Id),
    CONSTRAINT fk_ticket_tech FOREIGN KEY (TechnicianId) REFERENCES Users(Id)
);

-- 4. جدول تتبع حالات التذاكر (TicketLogs)
-- لتسجيل سجل تاريخي لكل تغيير يحدث على حالة التذاكر (مهم جداً للمراجعة والشفافية).
CREATE TABLE TicketLogs (
    Id NUMBER GENERATED BYقطع AS IDENTITY PRIMARY KEY,
    TicketId NUMBER NOT NULL,
    OldStatus VARCHAR2(50),
    NewStatus VARCHAR2(50) NOT NULL,
    Notes VARCHAR2(500),
    ChangedBy NUMBER NOT NULL,
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_log_ticket FOREIGN KEY (TicketId) REFERENCES MaintenanceTickets(Id) ON DELETE CASCADE,
    CONSTRAINT fk_log_user FOREIGN KEY (ChangedBy) REFERENCES Users(Id)
);

-- 5. جدول قطع الغيار والمخزون (InventoryParts)
-- لإدارة قطع الغيار المتاحة في الورشة وأسعارها والكميات.
CREATE TABLE InventoryParts (
    Id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PartName VARCHAR2(100) NOT NULL,
    PartCode VARCHAR2(50) NOT NULL UNIQUE,
    UnitPrice NUMBER(10, 2) NOT NULL,
    StockQuantity NUMBER(5) NOT NULL,
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 6. جدول القطع المستخدمة في الصيانة (TicketParts)
-- جدول وسيط (Many-to-Many) يربط التذاكر بقطع الغيار المستخدمة في إصلاح الجهاز.
CREATE TABLE TicketParts (
    Id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TicketId NUMBER NOT NULL,
    PartId NUMBER NOT NULL,
    Quantity NUMBER(3) DEFAULT 1 NOT NULL,
    UnitPriceAtTime NUMBER(10, 2) NOT NULL, -- سعر القطعة وقت تركيبها (لتجنب تغير السعر المستقبلي)
    CONSTRAINT fk_tp_ticket FOREIGN KEY (TicketId) REFERENCES MaintenanceTickets(Id) ON DELETE CASCADE,
    CONSTRAINT fk_tp_part FOREIGN KEY (PartId) REFERENCES InventoryParts(Id)
);

-- 7. جدول الفواتير (Invoices)
-- لتوليد الفواتير النهائية بعد انتهاء الصيانة.
CREATE TABLE Invoices (
    Id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TicketId NUMBER NOT NULL UNIQUE,
    TotalAmount NUMBER(10, 2) NOT NULL,
    PaymentStatus VARCHAR2(30) DEFAULT 'Unpaid', -- Unpaid, Paid, Refunded
    PaymentMethod VARCHAR2(30),                 -- Cash, CreditCard, ApplePay
    IssuedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_inv_ticket FOREIGN KEY (TicketId) REFERENCES MaintenanceTickets(Id) ON DELETE CASCADE
);
